function localPostgresAvailable(): boolean {
  try {
    execFileSync(
      'su',
      [
        'postgres',
        '-c',
        `psql 'postgres:///postgres?host=/var/run/postgresql' -t -c 'select 1'`,
      ],
      { timeout: 15000, stdio: 'pipe' }
    );
    return true;
  } catch {
    return false;
  }
}

const canVerifyDb = localPostgresAvailable();

describe('migrations against a real Postgres', () => {
  it.skipIf(!canVerifyDb)(
    'apply cleanly (idempotent re-apply) and satisfy the schema contract',
    () => {
      // The postgres OS user cannot traverse the repo's home directories,
      // so stage a world-readable copy of the script + migrations + tests.
      const stage = mkdtempSync(join(tmpdir(), 'sky-verify-'));
      try {
        cpSync(join(root, 'scripts'), join(stage, 'scripts'), {
          recursive: true,
        });
        cpSync(join(root, 'supabase'), join(stage, 'supabase'), {
          recursive: true,
        });
        // Behavioral cross-check the static tests cannot do: every skill code
        // the games can report must be accepted by the real
        // record_game_attempts (unknown codes raise and drop the batch).
        // Appended inside game_learning.test.sql's transaction so the
        // fixtures and auth context are in place.
        const sweepPath = join(stage, 'supabase', 'tests', 'game_learning.test.sql');
        const codes = GAME_SKILL_CODES.map((c) => `'${c}'`).join(',');
        const sweep = `
-- ---- generated by tests/migrations.test.ts: skill-code acceptance sweep --
-- (the file's tail runs as anon for permission tests; switch back)
reset role;
set local role authenticated;
set local request.jwt.claim.sub = '00000000-0000-0000-0000-00000000000a';
do $$
declare
  r jsonb;
begin
  r := public.record_game_attempts(
    '00000000-0000-0000-0000-0000000000c1', 'skill-sweep',
    (select jsonb_agg(jsonb_build_object('skill', code, 'correct', true, 'level', 1))
     from unnest(array[${codes}]) as code));
  assert (r ->> 'recorded')::int = ${GAME_SKILL_CODES.length},
    format('skill sweep recorded %s of %s codes', r ->> 'recorded', ${GAME_SKILL_CODES.length});
end $$;
`;
        const sql = readFileSync(sweepPath, 'utf8');
        // Replacer function (not a string): String.replace interprets $$
        // in a string replacement as an escaped $, which would mangle the
        // do $$ blocks.
        writeFileSync(
          sweepPath,
          sql.replace(/rollback;\s*$/, () => `${sweep}\nrollback;\n`)
        );
        execFileSync('chmod', ['-R', 'a+rX', stage]);
        const out = execFileSync(
          'su',
          [
            'postgres',
            '-c',
            `env DATABASE_URL='postgres:///postgres?host=/var/run/postgresql' ${process.execPath} ${join(stage, 'scripts', 'verify-db.mjs')}`,
          ],
          { timeout: 600000, encoding: 'utf8', stdio: 'pipe' }
        );
        expect(out).toContain('migrations applied (pass 1)');
        expect(out).toContain('migrations applied (pass 2)');
        expect(out).toContain('ok   schema_contract.test.sql');
        expect(out).toContain('ok   content_quality.test.sql');
        expect(out).toContain('ok   game_learning.test.sql');
      } finally {
        rmSync(stage, { recursive: true, force: true });
      }
    },
    600000
  );

  it.skipIf(canVerifyDb)('reports when local Postgres is unavailable', () => {
    // Placeholder so the skip is visible instead of silent.
    expect(canVerifyDb).toBe(false);
  });
});

