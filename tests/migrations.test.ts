/**
 * Migration honesty tests.
 *
 * The old version of this file grepped the migration SQL as text
 * ("create policy", "security definer", …). Those assertions are now
 * executed against a real throwaway Postgres instead:
 * scripts/verify-db.mjs applies every migration in order (twice, for the
 * idempotent range) and runs supabase/tests/*.test.sql, which assert the
 * RLS posture, the RPC surface, and the seeded rows against the live
 * catalogs. See supabase/tests/schema_contract.test.sql.
 */
